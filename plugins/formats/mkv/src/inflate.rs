    fn script() -> Vec<u8> {
        (0..60)
            .flat_map(|i| {
                format!("{i},0,Default,,0,0,0,,Line number {} of the script, with words.\\N", i * 7)
                    .into_bytes()
            })
            .collect()
    }

    fn inflate_all(src: &[u8], limit: usize) -> Result<Vec<u8>, InflateError> {
        let mut out = Vec::new();
        zlib_inflate(src, &mut out, limit).map(|_| out)
    }

    #[test]
    fn each_block_type_inflates_to_what_was_compressed() {
        assert_eq!(inflate_all(FIXED, 1 << 20).unwrap(), b"hello hello hello hello world");
        assert_eq!(inflate_all(STORED, 1 << 20).unwrap(), b"stored block bytes");
        assert_eq!(inflate_all(EMPTY, 1 << 20).unwrap(), b"");
        assert_eq!(inflate_all(DYNAMIC, 1 << 20).unwrap(), script());
        assert!(DYNAMIC[2] & 0x06 == 0x04, "the vector is a dynamic block");
    }

    #[test]
    fn output_is_appended_and_distances_stay_inside_this_stream() {
        let mut out = b"prefix".to_vec();
        zlib_inflate(FIXED, &mut out, 1 << 20).unwrap();
        assert_eq!(&out, b"prefixhello hello hello hello world");
    }

    #[test]
    fn a_bomb_stops_at_the_limit() {
        let mut out = Vec::new();
        assert_eq!(
            zlib_inflate(BOMB, &mut out, 64 << 10),
            Err(InflateError::TooLarge { limit: 64 << 10 })
        );
        assert!(out.len() <= 64 << 10);
        assert_eq!(
            inflate_all(BOMB, 1_000_000).unwrap().len(),
            1_000_000,
            "exactly the limit passes"
        );
        assert!(inflate_all(BOMB, 999_999).is_err());
    }

    #[test]
    fn a_bad_header_trailer_or_cut_is_an_error() {
        assert_eq!(inflate_all(&[0x78], 99), Err(InflateError::Truncated));
        assert_eq!(inflate_all(&[0x79, 0xda, 0x03, 0x00], 99), Err(InflateError::Header), "CM 9");
        assert_eq!(inflate_all(&[0x78, 0xdb, 0x03, 0x00], 99), Err(InflateError::Header), "FCHECK");
        assert_eq!(inflate_all(&[0x78, 0xbb, 0x03, 0x00], 99), Err(InflateError::Header), "FDICT");
        let mut sum = FIXED.to_vec();
        *sum.last_mut().unwrap() ^= 1;
        assert_eq!(inflate_all(&sum, 99), Err(InflateError::Checksum));
        for cut in 0..DYNAMIC.len() {
            assert!(inflate_all(&DYNAMIC[..cut], 1 << 20).is_err(), "cut at {cut}");
        }
        let mut stored = STORED.to_vec();
        stored[5] ^= 1;
        assert_eq!(inflate_all(&stored, 99), Err(InflateError::StoredLength));
        assert_eq!(inflate_all(&[0x78, 0xda, 0x07, 0x00], 99), Err(InflateError::BlockType));
    }

    #[test]
    fn corrupted_streams_never_panic_or_pass_the_limit() {
        let mut seed = 0x9E37_79B9_7F4A_7C15u64;
        for _ in 0..4000 {
            let mut bad = DYNAMIC.to_vec();
            for _ in 0..3 {
                seed ^= seed << 13;
                seed ^= seed >> 7;
                seed ^= seed << 17;
                let at = (seed % bad.len() as u64) as usize;
                bad[at] ^= 1 << (seed >> 61);
            }
            let mut out = Vec::new();
            let _ = zlib_inflate(&bad, &mut out, 8192);
            assert!(out.len() <= 8192);
        }
    }

    #[test]
    fn adler32_matches_rfc1950() {
        assert_eq!(adler32(b""), 1);
        assert_eq!(adler32(b"Wikipedia"), 0x11E6_0398);
        let long = vec![0xFFu8; 100_000];
        let (mut a, mut b) = (1u64, 0u64);
        for &x in &long {
            a = (a + x as u64) % 65_521;
            b = (b + a) % 65_521;
        }
        assert_eq!(adler32(&long), (b << 16 | a) as u32);
    }
