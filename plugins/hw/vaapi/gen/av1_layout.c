// Prints the libva AV1 encode layouts as Rust constants, for src/av1enc/layout.rs.
// `cargo xtask layout vaapi-av1` compiles and runs it.
// Offsets are bytes, a bitfield is (shift, width) in its union's value.
#include <stdio.h>
#include <stddef.h>
#include <string.h>
#include <va/va.h>
#include <va/va_enc_av1.h>

#define SIZE(T, name) printf("pub const %s: usize = %zu;\n", name, sizeof(T))
#define OFF(T, f, name) printf("pub const %s: usize = %zu;\n", name, offsetof(T, f))

static void bit(const char *name, unsigned long long value) {
    int shift = __builtin_ctzll(value), width = 0;
    while (value >> (shift + width) & 1) width++;
    printf("pub const %s: (u32, u32) = (%d, %d);\n", name, shift, width);
}

// set the field to all ones, read where its bits land
#define BITS(T, member, field, name) do { T x; memset(&x, 0, sizeof x); x.member.bits.field = ~0u; bit(name, x.member.value); } while (0)
#define FIELDS(T, member, field, name) do { T x; memset(&x, 0, sizeof x); x.member.fields.field = ~0u; bit(name, x.member.value); } while (0)

