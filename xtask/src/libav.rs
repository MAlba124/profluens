//! `libav-config <target>`, sys/libav-sys/config/<target>/ from an out-of-tree configure of the
//! FFmpeg submodule. Run once per target and commit, build.rs never runs configure.

use std::fs::{self, File};
use std::path::Path;
use std::process::{Command, Stdio};

use crate::error::Error;
use crate::util;

/// Decoders, their parsers and the AAC encoder, LGPL only.
const COMMON: &[&str] = &[
    "--enable-pic",
    "--disable-everything",
    "--disable-autodetect",
    "--disable-programs",
    "--disable-doc",
    "--disable-avdevice",
    "--disable-avformat",
    "--disable-avfilter",
    "--disable-swscale",
    "--disable-swresample",
    "--disable-network",
    "--disable-iconv",
    "--disable-debug",
    "--disable-symver",
    "--disable-pixelutils",
    "--enable-decoder=h264,hevc,vp8,vp9,aac,ac3,eac3,mp3float,dca,truehd,mlp,mpeg2video,mpeg4,vorbis,alac,flv,vp6,vp6f,vp6a,vp7,theora,speex",
    "--enable-parser=h264,hevc,vp8,vp9,aac,ac3,mpegaudio,dca,mlp,mpegvideo",
    "--enable-encoder=aac",
];

fn target_flags(target: &str) -> Result<Vec<String>, Error> {
    match target {
        "x86_64-unknown-linux-gnu" => {
            let cc = std::env::var("CC")
                .ok()
                .filter(|c| !c.is_empty())
                .unwrap_or_else(|| "clang".into());
            Ok(vec![format!("--cc={cc}"), "--target-os=linux".into(), "--arch=x86_64".into()])
        }
        // Not generated yet. Run this on (or cross to) the target with its compiler.
        "aarch64-linux-android" => {
            Err(Error::Missing("add the android NDK configure flags here".into()))
        }
        "aarch64-apple-darwin" => Err(Error::Missing("add the darwin configure flags here".into())),
        _ => Err(Error::Usage(format!("unknown target {target}"))),
    }
}

fn values<'a>(mak: &'a str, var: &str) -> Vec<&'a str> {
    mak.lines().filter_map(|l| l.strip_prefix(var)?.strip_prefix('=')).collect()
}

fn pick(mak: &str, var: &str) -> String {
    let mut out = String::new();
    for word in values(mak, var).iter().flat_map(|v| v.split(' ')) {
        if !word.is_empty() && !word.starts_with("-W") {
            out.push_str(word);
            out.push(' ');
        }
    }
    out
}

fn flags_txt(mak: &str) -> String {
    format!(
        "cppflags {}\ncflags {}\nx86asmflags {}\nextralibs {}\nconfigure {}\n",
        pick(mak, "CPPFLAGS"),
        pick(mak, "CFLAGS"),
        pick(mak, "X86ASMFLAGS"),
        values(mak, "EXTRALIBS-avcodec").join("\n").trim_end_matches('\n'),
        values(mak, "FFMPEG_CONFIGURATION").join("\n").trim_end_matches('\n'),
    )
}

fn ffversion_h(version: &str) -> String {
    format!(
        "/* Automatically generated by version.sh, do not manually edit! */\n\
         #ifndef AVUTIL_FFVERSION_H\n\
         #define AVUTIL_FFVERSION_H\n\
         #define FFMPEG_VERSION \"{version}\"\n\
         #endif /* AVUTIL_FFVERSION_H */\n"
    )
}

const COPIES: [&str; 8] = [
    "config.h",
    "config_components.h",
    "config.asm",
    "config_components.asm",
    "libavutil/avconfig.h",
    "libavcodec/codec_list.c",
    "libavcodec/parser_list.c",
    "libavcodec/bsf_list.c",
];

pub fn config(root: &Path, target: &str) -> Result<(), Error> {
    let here = root.join("sys/libav-sys");
    let ffsrc = here.join("ffmpeg");
    let out = here.join("config").join(target);
    if !ffsrc.join("configure").is_file() {
        return Err(Error::Missing(format!(
            "{} is empty, run git submodule update --init --depth 1",
            ffsrc.display()
        )));
    }
    let per = target_flags(target)?;
    let build = util::temp_dir("libav")?;
    let log = build.path.join("configure.out");
    let log_file = File::create(&log).map_err(|e| util::io_err(&log, e))?;
    let mut configure = Command::new(ffsrc.join("configure"));
    configure.current_dir(&build.path).args(&per).args(COMMON).stdout(Stdio::from(log_file));
    util::run_live("configure", &mut configure)?;

    if out.exists() {
        fs::remove_dir_all(&out).map_err(|e| util::io_err(&out, e))?;
    }
    util::mkdir_p(&out.join("libavutil"))?;
    util::mkdir_p(&out.join("libavcodec"))?;
    for f in COPIES {
        util::copy(&build.path.join(f), &out.join(f))?;
    }
    let release = String::from_utf8_lossy(&util::read(&ffsrc.join("RELEASE"))?).into_owned();
    let version = release.trim_end_matches('\n');
    util::write(&out.join("libavutil/ffversion.h"), ffversion_h(version).as_bytes())?;

    let mak_path = build.path.join("ffbuild/config.mak");
    let mak = String::from_utf8_lossy(&util::read(&mak_path)?).into_owned();
    util::write(&out.join("flags.txt"), flags_txt(&mak).as_bytes())?;

    let mut objlist = Command::new("python3");
    objlist.arg("-I").arg(here.join("tools/objlist.py")).arg(&ffsrc).arg(&build.path);
    let sources = util::capture("objlist.py", &mut objlist)?;
    util::write(&out.join("sources.txt"), &sources)?;
    let n = sources.iter().filter(|&&b| b == b'\n').count();
    println!("{n} sources for {target}");
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    const MAK: &str = "CPPFLAGS= -D_ISOC11_SOURCE -Wall -I. \n\
                       CFLAGS=   -std=c17 -fomit-frame-pointer -pthread -Wdeclaration-after-statement\n\
                       CFLAGS-foo=-nope\n\
                       X86ASMFLAGS=-f elf64 -g dwarf2\n\
                       EXTRALIBS-avcodec=-pthread -lm\n\
                       FFMPEG_CONFIGURATION=--enable-pic --disable-everything\n";

    #[test]
    fn flags_leave_warnings_out() {
        assert_eq!(pick(MAK, "CPPFLAGS"), "-D_ISOC11_SOURCE -I. ");
        assert_eq!(pick(MAK, "CFLAGS"), "-std=c17 -fomit-frame-pointer -pthread ");
        assert_eq!(pick(MAK, "NONE"), "");
        assert_eq!(
            flags_txt(MAK),
            "cppflags -D_ISOC11_SOURCE -I. \n\
             cflags -std=c17 -fomit-frame-pointer -pthread \n\
             x86asmflags -f elf64 -g dwarf2 \n\
             extralibs -pthread -lm\n\
             configure --enable-pic --disable-everything\n"
        );
    }

    #[test]
    fn the_version_header_is_what_version_sh_writes() {
        assert!(ffversion_h("9.0.2").contains("#define FFMPEG_VERSION \"9.0.2\"\n#endif"));
    }

    #[test]
    fn only_linux_x86_64_is_generated() {
        assert!(target_flags("x86_64-unknown-linux-gnu").is_ok());
        assert!(target_flags("aarch64-apple-darwin").is_err());
        assert!(target_flags("riscv").is_err());
    }
}
